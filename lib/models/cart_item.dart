class CartItem {
  final String image;
  final String title;
  final String size;
  final double rating;
  final String ratingsCount;
  final String price;
  final String originalPrice;
  final String deliveryInfo;

  CartItem({
    required this.image,
    required this.title,
    required this.size,
    required this.rating,
    required this.ratingsCount,
    required this.price,
    required this.originalPrice,
    required this.deliveryInfo,
  });
}